package mount

import (
	"fmt"
	"os"
)

var (
	dns    = "8.8.8.8"
	resolv = fmt.Sprintf("# Generated by ctrz\nnameserver %s\n", dns)
)

func Etc() error {
	if err := os.MkdirAll("/etc", 0o555); err != nil {
		return fmt.Errorf("Error creating etc directory: %v\n", err)
	}

	if err := os.WriteFile("/etc/resolv.conf", []byte(resolv), 0o644); err != nil {
		return fmt.Errorf("Error writing resolv.conf file: %v\n", err)
	}

	return nil
}
